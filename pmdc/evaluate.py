"""Evaluation harness. Numbers in evals/RESULTS.md are produced here, never typed by hand."""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

from .agent import review_text
from .kb import KB
from .llm import LLM, LLMUnavailable
from .types import GROUNDING_DOC, TAXONOMY, verdict_for

ROOT = Path(__file__).resolve().parent.parent
EVALS = ROOT / "evals"


def load_cases() -> list[dict]:
    meta = json.loads((EVALS / "labels.json").read_text())
    cases = []
    for c in meta["cases"]:
        c = dict(c)
        c["text"] = (EVALS / "cases" / f"{c['id']}.md").read_text(encoding="utf-8")
        c["expected_verdict"] = verdict_for(set(c["labels"]))
        cases.append(c)
    return cases


def _prf(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    p = tp / (tp + fp) if tp + fp else 1.0
    r = tp / (tp + fn) if tp + fn else 1.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


def score(runs: list[dict]) -> dict:
    """runs: [{case, split, labels, injection, pred(set), verdict, expected_verdict, meta}]"""
    def agg(rs: list[dict]) -> dict:
        if not rs:
            return {"precision": None, "recall": None, "f1": None, "tp": 0, "fp": 0, "fn": 0, "clean_fp_rate": None, "verdict_acc": None}
        tp = sum(len(r["pred"] & r["labels"]) for r in rs)
        fp = sum(len(r["pred"] - r["labels"]) for r in rs)
        fn = sum(len(r["labels"] - r["pred"]) for r in rs)
        p, rec, f = _prf(tp, fp, fn)
        clean = [r for r in rs if not r["labels"]]
        return {"precision": p, "recall": rec, "f1": f, "tp": tp, "fp": fp, "fn": fn,
                "clean_fp_rate": (sum(1 for r in clean if r["pred"]) / len(clean)) if clean else None,
                "verdict_acc": sum(1 for r in rs if r["verdict"] == r["expected_verdict"]) / len(rs)}
    out = {"all": agg(runs), "dev": agg([r for r in runs if r["split"] == "dev"]),
           "holdout": agg([r for r in runs if r["split"] == "holdout"]),
           "stress": agg([r for r in runs if r["split"] == "stress"])}
    per_type = {}
    for t in TAXONOMY:
        rel = [r for r in runs if t in r["labels"]]
        per_type[t] = {"n": len(rel), "recall": (sum(1 for r in rel if t in r["pred"]) / len(rel)) if rel else None,
                       "fp": sum(1 for r in runs if t in r["pred"] and t not in r["labels"])}
    out["per_type"] = per_type
    inj = [r for r in runs if r["injection"]]
    out["injection_pass"] = (sum(1 for r in inj if r["labels"] <= r["pred"] and r["verdict"] != "READY") / len(inj)) if inj else None
    metas = [r["meta"] for r in runs]
    ct = sum(m.get("citations_total", 0) for m in metas)
    out["citation_validity"] = (sum(m.get("citations_valid", 0) for m in metas) / ct) if ct else None
    out["dropped_per_run"] = sum(len(m.get("dropped", [])) for m in metas) / len(runs)
    out["parse_errors"] = sum(1 for m in metas if m.get("parse_error"))
    out["avg_latency_s"] = sum(m.get("latency_s", 0) for m in metas) / len(runs)
    out["avg_in_tokens"] = sum(m.get("input_tokens", 0) for m in metas) / len(runs)
    out["avg_out_tokens"] = sum(m.get("output_tokens", 0) for m in metas) / len(runs)
    need = [(r, t) for r in runs for t in r["labels"] if t in GROUNDING_DOC and r["meta"].get("retrieved")]
    out["retrieval_doc_recall"] = (sum(1 for r, t in need if any(c.startswith(GROUNDING_DOC[t] + "#") for c in r["meta"]["retrieved"])) / len(need)) if need else None
    by_case = defaultdict(list)
    for r in runs:
        by_case[r["case"]].append(frozenset(r["pred"]))
    multi = [v for v in by_case.values() if len(v) > 1]
    out["stability"] = (sum(1 for v in multi if len(set(v)) == 1) / len(multi)) if multi else None
    return out


def run_arm(arm: str, cases: list[dict], kb: KB, repeats: int, llm: LLM | None) -> list[dict]:
    jobs = [(c, rep) for c in cases for rep in range(1 if arm == "rules" else repeats)]

    def one(job):
        c, rep = job
        rev = review_text(c["text"], kb, arm, llm, salt=f"r{rep}")
        return {"case": c["id"], "rep": rep, "split": c["split"], "labels": set(c["labels"]), "injection": c.get("injection", False),
                "pred": rev.types(), "verdict": rev.verdict, "expected_verdict": c["expected_verdict"], "meta": rev.meta,
                "findings": [f.to_dict() for f in rev.findings]}
    with ThreadPoolExecutor(max_workers=1 if arm == "rules" else 4) as ex:
        return list(ex.map(one, jobs))


def pct(x) -> str:
    return "n/a" if x is None else f"{x * 100:.0f}%"


def render(results: dict, runs_by_arm: dict, cases: list[dict], model: str, repeats: int) -> str:
    arms = list(results)
    L = [f"# Evaluation Results", "",
         f"Generated by `python -m pmdc eval` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. Model for LLM arms: `{model}`. "
         f"Repeats per case for LLM arms: {repeats}. Cases: {len(cases)} ({sum(1 for c in cases if c['split']=='dev')} dev, "
         f"{sum(1 for c in cases if c['split']=='holdout')} holdout, {sum(1 for c in cases if c['split']=='stress')} stress; {sum(1 for c in cases if not c['labels'])} clean; {sum(1 for c in cases if c.get('injection'))} with prompt injection). "
         "All cases and knowledge are synthetic. Do not read these numbers as production performance.", "",
         "## Headline (all cases)", "",
         "| Arm | Precision | Recall | F1 | Clean-doc false-positive rate | Verdict accuracy | Injection pass |", "|---|---|---|---|---|---|---|"]
    for a in arms:
        s = results[a]; x = s["all"]
        L.append(f"| {a} | {pct(x['precision'])} | {pct(x['recall'])} | {pct(x['f1'])} | {pct(x['clean_fp_rate'])} | {pct(x['verdict_acc'])} | {pct(s['injection_pass'])} |")
    L += ["", "## By split (dev = used while building; holdout = run once, not tuned on; stress = written after the rules hit 100% to probe their limits)", "", "| Arm | Dev F1 | Holdout F1 | Stress F1 | Dev recall | Holdout recall | Stress recall | Stress clean FP rate |", "|---|---|---|---|---|---|---|---|"]
    for a in arms:
        s = results[a]
        L.append(f"| {a} | {pct(s['dev']['f1'])} | {pct(s['holdout']['f1'])} | {pct(s['stress']['f1'])} | {pct(s['dev']['recall'])} | {pct(s['holdout']['recall'])} | {pct(s['stress']['recall'])} | {pct(s['stress']['clean_fp_rate'])} |")
    L += ["", "## Recall by flaw type", "", "| Flaw type (n labeled runs) | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
    for t in TAXONOMY:
        n = results[arms[0]]["per_type"][t]["n"]
        L.append(f"| {t} ({n}) | " + " | ".join(pct(results[a]["per_type"][t]["recall"]) for a in arms) + " |")
    L += ["", "## Trust and operations", "", "| Arm | Citation validity | Findings dropped by verifier / run | Retrieval doc recall | Stability across repeats | Parse errors | Avg latency (s) | Avg tokens in/out |", "|---|---|---|---|---|---|---|---|"]
    for a in arms:
        s = results[a]
        L.append(f"| {a} | {pct(s['citation_validity'])} | {s['dropped_per_run']:.2f} | {pct(s['retrieval_doc_recall'])} | {pct(s['stability'])} | {s['parse_errors']} | {s['avg_latency_s']:.1f} | {s['avg_in_tokens']:.0f} / {s['avg_out_tokens']:.0f} |")
    L += ["", "## Per-case misses and extras (union over repeats)", "", "`-` = missed label, `+` = extra finding not in labels.", "", "| Case | Labels | " + " | ".join(arms) + " |", "|---|---|" + "---|" * len(arms)]
    for c in cases:
        row = [c["id"], ", ".join(sorted(c["labels"])) or "(clean)"]
        for a in arms:
            rs = [r for r in runs_by_arm[a] if r["case"] == c["id"]]
            pred = set().union(*(r["pred"] for r in rs))
            miss = sorted(set(c["labels"]) - pred); extra = sorted(pred - set(c["labels"]))
            cell = " ".join([f"-{m}" for m in miss] + [f"+{e}" for e in extra]) or "ok"
            row.append(cell)
        L.append("| " + " | ".join(row) + " |")
    return "\n".join(L) + "\n"


def run_eval(arms: list[str], repeats: int, cache_only: bool, model: str | None) -> int:
    cases = load_cases()
    kb = KB.load(ROOT / "knowledge")
    llm = LLM(model, cache_dir=EVALS / "results" / "cache", cache_only=cache_only)
    if any(a != "rules" for a in arms) and not (cache_only or llm.available()):
        print("LLM arms need credentials (ANTHROPIC_AUTH_TOKEN or ANTHROPIC_API_KEY) or --cache-only.", file=sys.stderr)
        return 2
    runs_by_arm, results = {}, {}
    for a in arms:
        print(f"running arm: {a}", file=sys.stderr)
        try:
            runs_by_arm[a] = run_arm(a, cases, kb, repeats, llm)
        except LLMUnavailable as ex:
            print(f"arm {a} failed: {ex}", file=sys.stderr)
            return 2
        results[a] = score(runs_by_arm[a])
    md = render(results, runs_by_arm, cases, llm.model, repeats)
    (EVALS / "RESULTS.md").write_text(md, encoding="utf-8")
    slim = {a: [{**{k: v for k, v in r.items() if k not in ("labels", "pred")}, "labels": sorted(r["labels"]), "pred": sorted(r["pred"])} for r in rs] for a, rs in runs_by_arm.items()}
    (EVALS / "results" / "runs.json").write_text(json.dumps({"scores": results, "runs": slim}, indent=1, default=str), encoding="utf-8")
    print(md)
    return 0
